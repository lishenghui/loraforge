"""Benchmark-only gfx90a NF4/BF16-LoRA support for the fused 0.8B fixture."""

import ast
import json
import textwrap
from pathlib import Path


def extended_verify_source(source):
    tree = ast.parse(textwrap.dedent(source))
    changed = 0
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "rocm_supported_quantization"
            for t in node.targets
        ):
            assert isinstance(node.value, ast.List)
            assert not any(
                isinstance(v, ast.Constant) and v.value == "bitsandbytes"
                for v in node.value.elts
            )
            node.value.elts.append(ast.Constant(value="bitsandbytes"))
            changed += 1
    assert changed == 1, changed
    return ast.unparse(ast.fix_missing_locations(tree))


def adapter_load_config(config):
    """Keep the base loader intact; BF16 adapter files use ordinary safetensors."""
    from dataclasses import replace

    if getattr(config.load_format, "value", config.load_format) != "bitsandbytes":
        return config
    return replace(config, load_format="safetensors")


def install():
    import inspect
    from functools import wraps

    import torch
    from sglang import __version__

    assert __version__ == "0.5.22"
    from sglang.srt.configs.model_config import ModelConfig
    from sglang.srt.models.qwen3_5 import (
        Qwen3_5ForCausalLM,
        Qwen3_5ForConditionalGeneration,
    )

    if getattr(ModelConfig, "_lf_nf4_admission", False):
        return
    original = ModelConfig._verify_quantization
    source = extended_verify_source(inspect.getsource(original))
    namespace = dict(original.__globals__)
    exec(compile(source, "<isolated-gfx90a-nf4-admission>", "exec"), namespace)
    extended = namespace[original.__name__]

    @wraps(original)
    def verify(self):
        if self.quantization != "bitsandbytes":
            return original(self)
        receipt_path = Path(self.model_path) / "quantization-receipt.json"
        if not receipt_path.is_file():
            raise ValueError(
                "use the 114-projection fused NF4 fixture generated by prepare_qwen35_nf4.py"
            )
        receipt = json.loads(receipt_path.read_text())
        assert (
            receipt.get("state") == "complete"
            and len(receipt.get("quantized_layers", [])) == 114
        )
        cfg = getattr(self.hf_config, "quantization_config", {})
        assert self.hf_config.model_type in ("qwen3_5", "qwen3_5_text")
        assert (
            self.dtype == torch.bfloat16 and cfg.get("quant_method") == "bitsandbytes"
        )
        assert cfg.get("load_in_4bit") is True and cfg.get("load_in_8bit") is False
        assert (
            cfg.get("bnb_4bit_quant_type") == "nf4"
            and cfg.get("bnb_4bit_compute_dtype") == "bfloat16"
        )
        assert cfg.get("bnb_4bit_use_double_quant") is True
        assert (
            torch.version.hip
            and torch.cuda.get_device_properties(0).gcnArchName.split(":")[0]
            == "gfx90a"
        )
        return extended(self)

    ModelConfig._verify_quantization = verify
    ModelConfig._lf_nf4_admission = True
    for cls in (Qwen3_5ForCausalLM, Qwen3_5ForConditionalGeneration):
        # Checkpoint names already match fused runtime parameters; no shard remapping.
        cls.bitsandbytes_stacked_params_mapping = {}

    from sglang.srt.lora.lora import LoRAAdapter

    original_adapter_init = LoRAAdapter.__init__

    @wraps(original_adapter_init)
    def adapter_init(
        self, uid, config, base_hf_config, load_config, lora_backend, base_model=None
    ):
        return original_adapter_init(
            self,
            uid,
            config,
            base_hf_config,
            adapter_load_config(load_config),
            lora_backend,
            base_model=base_model,
        )

    LoRAAdapter.__init__ = adapter_init
